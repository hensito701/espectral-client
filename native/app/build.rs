//! Build script: compiles the Slint UI, embeds the i18n tables and, on Windows,
//! compiles the executable's icon + VERSIONINFO resource.
//!
//! * `ui/app.slint` -> Rust (slint::include_modules!()).
//! * Every `i18n/*.json` file is embedded (OUT_DIR/i18n_files.rs) — page
//!   agents add a file, nothing else to register.
//! * Every literal `T.tr*("key"` in `ui/**/*.slint` is checked against the
//!   tables: a missing key prints a cargo warning (the UI would show the key).
//! * Windows targets only: `icons/icon.ico` + a VERSIONINFO block are turned
//!   into a COFF object by windres and linked into the binary, so Explorer,
//!   the shortcut and Apps & Features show the real name/version/icon.

use std::collections::BTreeSet;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());

    // ---- Slint ----
    let config = slint_build::CompilerConfiguration::new().with_style("fluent".into());
    slint_build::compile_with_config(manifest.join("ui/app.slint"), config).expect("slint build failed");

    // ---- i18n ----
    let i18n_dir = manifest.join("i18n");
    println!("cargo:rerun-if-changed={}", i18n_dir.display());
    let mut files: Vec<PathBuf> = fs::read_dir(&i18n_dir)
        .expect("native/app/i18n missing")
        .filter_map(|e| e.ok().map(|e| e.path()))
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    files.sort();
    let mut known: BTreeSet<String> = BTreeSet::new();
    let mut src = String::from("/// (namespace, json) for every native/app/i18n/*.json — generated by build.rs\npub static I18N_FILES: &[(&str, &str)] = &[\n");
    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
        let text = fs::read_to_string(f).unwrap();
        let doc: serde_json::Value =
            serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: invalid JSON: {e}", f.display()));
        for lang in ["es", "en"] {
            match doc.get(lang).and_then(|v| v.as_object()) {
                Some(map) => known.extend(map.keys().cloned()),
                None => panic!("{}: missing \"{lang}\" object", f.display()),
            }
        }
        let ns = f.file_stem().unwrap().to_string_lossy();
        src.push_str(&format!("    ({ns:?}, include_str!({:?})),\n", f.display().to_string()));
    }
    src.push_str("];\n");
    fs::write(out.join("i18n_files.rs"), src).unwrap();

    // ---- missing-key lint ----
    let mut slint_files = Vec::new();
    collect_slint(&manifest.join("ui"), &mut slint_files);
    for f in slint_files {
        let text = fs::read_to_string(&f).unwrap_or_default();
        // ignore comment lines (usage examples)
        let code: String = text.lines().filter(|l| !l.trim_start().starts_with("//")).collect::<Vec<_>>().join("\n");
        for key in tr_keys(&code) {
            if !known.contains(&key) {
                println!(
                    "cargo:warning=i18n: key \"{key}\" used in {} is in no native/app/i18n/*.json",
                    f.strip_prefix(&manifest).unwrap_or(&f).display()
                );
            }
        }
    }

    // ---- Windows exe resources (icon + VERSIONINFO) ----
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        windows_resources(&manifest, &out);
    }
}

/// Compiles `icons/icon.ico` + a VERSIONINFO block into a COFF object and
/// links it into every binary of this crate.
///
/// windres is looked up as `$WINDRES`, then the mingw cross prefix used by
/// this project (`x86_64-w64-mingw32-windres`), then plain `windres` (MSYS2 /
/// Windows host). A missing compiler is a hard error: shipping an exe with no
/// version/icon resource would silently break the update UI (Explorer shows
/// "espectral-client" and no publisher) — better to fail the build.
fn windows_resources(manifest: &Path, out: &Path) {
    let version = std::env::var("CARGO_PKG_VERSION").unwrap_or_else(|_| "0.0.0".into());
    // The RC `FILEVERSION` tuple is numeric: 1.7.0 -> 1,7,0,0 (missing parts 0).
    let mut quad: Vec<u32> = version.split(['.', '-', '+']).take(4).map(|p| p.parse::<u32>().unwrap_or(0)).collect();
    quad.resize(4, 0);
    let (a, b, c, d) = (quad[0], quad[1], quad[2], quad[3]);

    let icon = manifest.join("icons/icon.ico");
    if !icon.is_file() {
        panic!("{} is missing — run `node scripts/make-icons.mjs`", icon.display());
    }
    println!("cargo:rerun-if-changed={}", icon.display());

    // windres reads the file with the system ANSI codepage unless told
    // otherwise; -c 65001 makes the UTF-8 source (© in LegalCopyright) come
    // out right. Escapes would be codepage-dependent, so the file is plain UTF-8.
    let rc = format!(
        r#"// Generated by native/app/build.rs — do not edit.
#include <winver.h>

1 ICON "{icon}"

1 VERSIONINFO
FILEVERSION {a},{b},{c},{d}
PRODUCTVERSION {a},{b},{c},{d}
FILEOS 0x00040004
FILETYPE 0x00000001
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904b0"
    BEGIN
      VALUE "CompanyName", "spectral"
      VALUE "FileDescription", "Espectral Client"
      VALUE "FileVersion", "{version}"
      VALUE "InternalName", "espectral-client"
      VALUE "LegalCopyright", "© 2026 Espectral Client"
      VALUE "OriginalFilename", "espectral-client.exe"
      VALUE "ProductName", "Espectral Client"
      VALUE "ProductVersion", "{version}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
"#,
        icon = icon.display().to_string().replace('\\', "/"),
    );
    let rc_path = out.join("espectral-client.rc");
    fs::write(&rc_path, rc).expect("failed to write the Windows resource script");
    let obj = out.join("espectral-client.res.o");

    let candidates: Vec<String> = std::env::var("WINDRES")
        .ok()
        .filter(|v| !v.trim().is_empty())
        .into_iter()
        .chain(["x86_64-w64-mingw32-windres".to_string(), "windres".to_string()])
        .collect();
    let mut errors = Vec::new();
    for tool in &candidates {
        // A quoted WINDRES value ("C:\Program Files\...\windres.exe") must stay one argv entry.
        let exe = tool.trim_matches('"');
        match Command::new(exe).args(["-c", "65001", "-O", "coff", "-o"]).arg(&obj).arg(&rc_path).status() {
            Ok(s) if s.success() => {
                println!("cargo:rustc-link-arg-bins={}", obj.display());
                println!("cargo:rerun-if-env-changed=WINDRES");
                return;
            }
            Ok(s) => errors.push(format!("{exe}: exited with {s}")),
            Err(e) => errors.push(format!("{exe}: {e}")),
        }
    }
    panic!(
        "windres is required to build the Windows client (icon + version resource) but none of \
         [{}] could compile {}. Install mingw-w64 (gcc-mingw-w64-x86-64 + binutils-mingw-w64-x86-64, \
         MSYS2, or the Windows GNU toolchain) and/or point $WINDRES at it.\n{}",
        candidates.join(", "),
        rc_path.display(),
        errors.join("\n")
    );
}

fn collect_slint(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(rd) = fs::read_dir(dir) else { return };
    for e in rd.flatten() {
        let p = e.path();
        if p.is_dir() {
            collect_slint(&p, out);
        } else if p.extension().is_some_and(|x| x == "slint") {
            out.push(p);
        }
    }
}

/// Literal keys of `T.tr("k"`, `T.tr1("k"`, `T.tr2("k"`, `T.tr3("k"`.
fn tr_keys(text: &str) -> Vec<String> {
    let mut keys = Vec::new();
    let mut rest = text;
    while let Some(i) = rest.find("T.tr") {
        rest = &rest[i + 4..];
        let r = rest.trim_start_matches(|c: char| c.is_ascii_digit());
        let Some(r) = r.strip_prefix("(\"") else { continue };
        if let Some(end) = r.find('"') {
            keys.push(r[..end].to_string());
        }
    }
    keys
}

#!/usr/bin/env python3
"""Regenerate ui/widgets/emoji.slint from ui/assets/emoji/index.json.

index.json maps an emoji string to its Twemoji file stem (codepoints joined
by '-', lowercase, without fe0f). Fetch new SVGs from
https://raw.githubusercontent.com/jdecked/twemoji/v15.1.0/assets/svg/<stem>.svg
"""
import json, pathlib
ui = pathlib.Path(__file__).resolve().parent.parent / 'ui'
idx = json.loads((ui / 'assets/emoji/index.json').read_text())
items = sorted(idx.items(), key=lambda kv: kv[1])
known = ' || '.join(f'char == "{e}"' for e, _ in items)
src = ''.join(f'\n            char == "{e}" ? @image-url("../assets/emoji/{c}.svg") :' for e, c in items)
out = f'''// GENERATED by scripts/gen-emoji.py from assets/emoji/index.json (Twemoji 15.1 SVGs,
// CC-BY 4.0, see assets/emoji/LICENSE-GRAPHICS.txt). Color emoji are drawn as images
// because femtovg / the software renderer have no color-emoji font support.
//
//     Emoji {{ char: "🎨"; size: 14px; }}
//
// Unknown characters fall back to plain text (system font). Foundation-owned file.

export component Emoji inherits Rectangle {{
    in property <string> char;
    in property <length> size: 16px;
    in property <brush> fallback-color: #ffffff;
    width: size;
    height: size;
    property <bool> known: {known};
    if known: Image {{
        width: root.size;
        height: root.size;
        image-fit: contain;
        source:{src} @image-url("");
    }}
    if !known: Text {{
        text: root.char;
        font-size: root.size * 0.9;
        color: root.fallback-color;
        horizontal-alignment: center;
        vertical-alignment: center;
    }}
}}
'''
(ui / 'widgets/emoji.slint').write_text(out)
print(f'{len(items)} emoji')

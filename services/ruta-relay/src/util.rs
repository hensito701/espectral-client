//! Clock and formatting helpers (no extra dependencies).

use std::time::{SystemTime, UNIX_EPOCH};

/// Seconds since the Unix epoch, clamped to 0 if the clock is before 1970.
pub fn now_unix() -> i64 {
    match SystemTime::now().duration_since(UNIX_EPOCH) {
        Ok(d) => d.as_secs() as i64,
        Err(_) => 0,
    }
}

/// RFC 3339 UTC timestamp with second precision, e.g. `2026-11-07T10:11:12Z`.
pub fn fmt_rfc3339(secs: i64) -> String {
    let days = secs.div_euclid(86_400);
    let rem = secs.rem_euclid(86_400);
    let (y, mo, d) = civil_from_days(days);
    format!(
        "{y:04}-{mo:02}-{d:02}T{:02}:{:02}:{:02}Z",
        rem / 3600,
        (rem % 3600) / 60,
        rem % 60
    )
}

/// Howard Hinnant's `civil_from_days`: days since 1970-01-01 -> (y, m, d).
fn civil_from_days(z: i64) -> (i64, u32, u32) {
    let z = z + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let doe = z - era * 146_097; // [0, 146096]
    let yoe = (doe - doe / 1_460 + doe / 36_524 - doe / 146_096) / 365; // [0, 399]
    let y = yoe + era * 400;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100); // [0, 365]
    let mp = (5 * doy + 2) / 153; // [0, 11]
    let d = (doy - (153 * mp + 2) / 5 + 1) as u32;
    let m = if mp < 10 { mp + 3 } else { mp - 9 } as u32;
    (if m <= 2 { y + 1 } else { y }, m, d)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn formats_known_instants() {
        assert_eq!(fmt_rfc3339(0), "1970-01-01T00:00:00Z");
        assert_eq!(fmt_rfc3339(1_700_000_000), "2023-11-14T22:13:20Z");
        assert_eq!(fmt_rfc3339(1_769_000_000), "2026-01-21T12:53:20Z");
        // Leap day.
        assert_eq!(fmt_rfc3339(1_709_164_800), "2024-02-29T00:00:00Z");
    }
}
